import assert from 'node:assert/strict';
import {consentPreflight} from '../services/one-crm-consent.mjs';
const tenantId='demo',asOf='2026-11-26T12:00:00Z',channel='email';
const p=(customerToken,status='active')=>({tenantId,customerToken,status});
const e=(customerToken,status,sourceEventId,patch={})=>({tenantId,customerToken,channel,purpose:'marketing',status,source:'demo-ledger',sourceEventId,at:'2026-11-20T12:00:00Z',proofRef:'demo-proof',proofVerified:true,...patch});
const profiles=[p('a'),p('b'),p('c'),p('d'),p('e'),p('f','quarantined'),p('g')];
const events=[e('a','granted','1'),e('b','granted','2'),e('b','revoked','3'),e('c','granted','4',{proofVerified:false}),e('d','granted','5'),e('f','granted','6'),e('g','granted','7',{channel:'sms'})];
const suppressions=[{tenantId,customerToken:'d',channel:'all',active:true}];
const run=(patch={})=>consentPreflight({tenantId,asOf,channel,profiles,events,suppressions,ledgerComplete:true,...patch});
const r=run();assert.equal(r.summary.eligible,1);assert.equal(r.summary.reasons.revoked,1);assert.equal(r.summary.reasons.proof_missing,1);assert.equal(r.summary.reasons.suppressed,1);assert.equal(r.summary.reasons.inactive,1);assert.equal(r.summary.reasons.unknown,2);assert.equal(r.summary.activationEnabled,false);
assert.equal(run({ledgerComplete:false}).summary.eligible,0);
assert.equal(run({events:[...events].reverse()}).summary.eligible,1);
assert.equal(run({events:[...events,e('a','revoked','8',{at:'2026-12-01T12:00:00Z'})]}).summary.eligible,1);
assert.equal(run({events:[...events,e('a','granted','8',{proofVerified:false})]}).summary.eligible,0);
assert.equal(run({events:[...events,e('a','granted','8',{at:'invalid'})]}).summary.reasons.invalid,1);
assert.equal(run({events:[...events,events[0]]}).summary.eligible,1);
assert.throws(()=>run({events:[...events,{...events[0],status:'revoked'}]}));
assert.throws(()=>run({events:[{...events[0],tenantId:'other'}]}));
assert.throws(()=>run({profiles:[...profiles,profiles[0]]}));
assert.throws(()=>run({suppressions:[{...suppressions[0],tenantId:'other'}]}));
assert.ok(!JSON.stringify(r.summary).includes('demo-proof'));
assert.equal(run({events:[...events,e('a','granted','8',{at:'2026-11-31T12:00:00Z'})]}).summary.reasons.invalid,1);
assert.equal(run({events:[...events,e('a','granted','8',{at:'2026-11-20T12:00:00.1Z'})]}).summary.eligible,1);
assert.throws(()=>run({asOf:'2026-02-30T12:00:00Z'}));
console.log('CRM consent preflight passed');
