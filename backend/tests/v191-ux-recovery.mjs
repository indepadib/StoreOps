import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'../..');
const read=p=>readFileSync(path.join(root,p),'utf8');
const css=read('frontend/experience-v191.css');
const enhancements=read('frontend/js/enhancements-entry.js');
const auth=read('frontend/js/auth-entry.js');
const development=read('frontend/js/pages/development.js');
const pwa=read('frontend/js/pwa.js');
assert.match(enhancements,/Opérations/,'visible Operations hub missing');
assert.match(enhancements,/installDirectorExperience/,'director navigation simplification missing');
assert.match(enhancements,/goPage\(b\.dataset\.opsPage\)/,'operations must navigate to canonical StoreOps pages');
assert.match(development,/DÉVELOPPEMENT RÉSEAU/,'canonical Development workspace missing');
assert.match(development,/GO/,'Development decision state missing');
assert.match(development,/CAPEX/,'Development business case missing');
assert.match(css,/ux191-board|ux191-grid/,'responsive V1.91 experience styles missing');
assert.doesNotMatch(enhancements,/\.\/ux-v191\.js/,'duplicate V1.91 Development renderer must not run');
assert.doesNotMatch(pwa,/\.\/development\.js/,'legacy Development renderer must not run');
const enhancementBuild=enhancements.match(/const BUILD='(\d+)'/)?.[1];
const authBuild=auth.match(/const BUILD='(\d+)'/)?.[1];
const importedEnhancementBuild=auth.match(/enhancements-entry\.js\?v=(\d+)/)?.[1];
assert(enhancementBuild&&Number(enhancementBuild)>=1920,'enhancement cache version must stay at or above V1.92 baseline');
assert(authBuild&&Number(authBuild)>=1920,'frontend runtime cache version must stay at or above V1.92 baseline');
assert.equal(importedEnhancementBuild,authBuild,'auth runtime must cache-bust the enhancement graph with its current BUILD');
console.log('V1.91 visible UX preserved through canonical V1.92+ runtime OK');
