import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';

const pkg=JSON.parse(readFileSync(new URL('../package.json',import.meta.url),'utf8'));
const config=readFileSync(new URL('../config.mjs',import.meta.url),'utf8');
const env=readFileSync(new URL('../../.env.example',import.meta.url),'utf8');
const server=readFileSync(new URL('../server.mjs',import.meta.url),'utf8');
const frontendApi=readFileSync(new URL('../../frontend/js/api.js',import.meta.url),'utf8');
const showcaseApi=readFileSync(new URL('../../frontend/js/api-showcase.js',import.meta.url),'utf8');
const netlifyBuild=readFileSync(new URL('../../frontend/netlify-build.sh',import.meta.url),'utf8');
const bootClassic=readFileSync(new URL('../../frontend/js/boot-classic.js',import.meta.url),'utf8');
assert.equal(pkg.version,'2.40.2');
assert.match(config,/STOREOPS_VERSION \|\| '2\.40\.2'/);
assert.match(env,/STOREOPS_VERSION=2\.40\.2/);
assert.match(server,/version:config\.appVersion/g);
assert.doesNotMatch(server,/version:'1\.10'|StoreOps V1\.10/);
assert.match(showcaseApi,/SHOWCASE_VERSION='2\.40\.2-showcase'/);
assert.match(netlifyBuild,/STOREOPS_RELEASE_BUILD="\$\{STOREOPS_RELEASE_BUILD:-2402\}"/,'Netlify build fallback must use V2.40.2 cache key');
assert.match(bootClassic,/var BUILD='2\.40\.2'/,'early boot watchdog must expose V2.40.2');
assert.match(frontendApi,/import\('\.\/api-showcase\.js'\)/,'live API facade must lazily load the versioned showcase runtime');
assert.doesNotMatch(frontendApi,/SHOWCASE_VERSION=/,'live API facade must stay free of showcase implementation constants');
console.log('StoreOps V2.40.2 version contract tests passed');
