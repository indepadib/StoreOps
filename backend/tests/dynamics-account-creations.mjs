const stores=[{id:'a'},{id:'b'}],settings=id=>({d365:{operatingUnitNumber:id}});
const account=(id,party,date='2026-11-02T10:00:00Z')=>({AccountNum:id,Party:party,SysDataAreaId:'5001',SysCreatedDateTime:date});
const card=(party,unit,date)=>({PartyNumber:party,OmOperatingUnitNumber:unit,LoyaltyEnrollmentDate:date});
const accounts=[account('one',1),account('one',1),account('two',2),account('three',3),account('four',4),account('old',5,'2026-10-31T22:59:59Z'),account('boundary',6,'2026-10-31T23:00:00Z')];
const parties=[1,2,3,4,5,6].map(n=>({SourceKey:n,PartyNumber:'p'+n}));
const cards=[card('p1','a','2026-11-03T12:00:00Z'),card('p1','b','2026-11-04T12:00:00Z'),card('p2','b','2026-11-10T12:00:00Z'),card('p3','a','2026-11-03T12:00:00Z'),card('p3','b','2026-11-03T12:00:00Z'),card('p6','a','2026-11-04T12:00:00Z')];
const options={company:'5001',startDate:'2026-11-01',endDate:'2026-11-30',settings,timeZone:'Europe/Paris'};
const result=aggregateAccountCreations(accounts,parties,cards,stores,options);
assert.equal(result.networkTotal,5);assert.equal(result.total,3);assert.equal(result.unattributed,2);
assert.deepEqual(result.stores,[{storeId:'a',total:2},{storeId:'b',total:1}]);
assert.equal(aggregateAccountCreations(accounts,parties,cards,[stores[1]],options).total,1,'changing selected stores must not change account attribution');
assert.throws(()=>aggregateAccountCreations([account('',1)],parties,cards,stores,options));
assert.throws(()=>aggregateAccountCreations([account('x',1,'bad')],parties,cards,stores,options));
