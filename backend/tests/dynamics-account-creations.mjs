import assert from 'node:assert/strict';
process.env.STOREOPS_DB=':memory:';
const {aggregateAccountCreations,businessMidnight,readCompleteCollection,readAccountCreations}=await import('../services/dynamics-account-creations.mjs');
assert.equal(businessMidnight('2026-11-01','Europe/Paris'),'2026-10-31T23:00:00.000Z');
assert.equal(businessMidnight('2026-03-01'),'2026-03-01T00:00:00.000Z');
