import assert from 'node:assert/strict';
import {mkdtempSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
process.env.STOREOPS_DB=join(mkdtempSync(join(tmpdir(),'same-time-')),'test.db');
const {applyCutoff,aggregateSalesRows,transactionMinute,salesIntegrationConfig}=await import('../services/dynamics-sales.mjs');
const {inferSalesTimeField}=await import('../services/d365-mapping-diagnostics.mjs');
const {salesExplanation,hourlyComparison}=await import('../services/sales-explanation.mjs');
const rows=[{transTime:32400,SysModifiedDateTime:'2026-10-09T08:00:00Z',tx:'1',amount:-2000,qty:10},{transTime:'64800',SysModifiedDateTime:'2026-10-09T08:00:00Z',tx:'2',amount:-18000,qty:40}];
assert.equal(inferSalesTimeField(rows),'transTime');
assert.equal(inferSalesTimeField([{SysModifiedDateTime:'2026-10-09T08:00:00Z',PickupStartTime:0}]),null);
assert.equal(salesIntegrationConfig().fields.time,'transTime');
assert.equal(transactionMinute('64800','transTime'),1080);
assert.equal(transactionMinute(rows[0].SysModifiedDateTime,'SysModifiedDateTime'),null);
const cut=applyCutoff(rows,'transTime',600);
assert.equal(cut.meta.applied,true);assert.equal(cut.rows.length,1);
const c=aggregateSalesRows(cut.rows,{sign:-1,fields:{transaction:'tx',net:'amount',quantity:'qty',time:'transTime'}});
assert.equal(c.netSales,2000);assert.equal(c.hourly[0].tickets,1);assert.equal(c.lastSaleMinute,540);
assert.equal(applyCutoff([...rows,{transTime:null}],'transTime',600).meta.complete,false);
const prior={netSales:3000,tickets:2,units:12,hourly:[{key:'9',sales:3000,tickets:2}]};
const analysis=salesExplanation(c,prior,{});
assert.equal(analysis.decomposition.ticketContribution+analysis.decomposition.basketContribution,-1000);
assert.equal(analysis.basketDrivers.quantityContribution+analysis.basketDrivers.priceMixContribution,500);
const hours=hourlyComparison(c,prior,600);
assert.equal(hours.length,11);assert.equal(hours.at(-1).currentCumulative,2000);assert.equal(hours.at(-1).previousCumulative,3000);assert.equal(hours.at(-1).partial,true);
assert.equal(salesExplanation(c,null).decomposition,null);
assert.equal(hourlyComparison(c,null,600)[0].previous,null);
console.log('PASS POS time vs integration time, string seconds, cutoff completeness, hourly reconciliation and exact CA/basket contributions');
