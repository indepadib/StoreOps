const mem=new Map();
globalThis.localStorage={getItem:k=>mem.has(k)?mem.get(k):null,setItem:(k,v)=>mem.set(k,String(v)),removeItem:k=>mem.delete(k)};
globalThis.window={STOREOPS_CONFIG:{mode:'showcase'}};
const {mockApi,resetShowcase}=await import('../../frontend/js/mock-api.js');
const ok=(v,m)=>{if(!v)throw new Error(m)};
const today=new Date().toISOString().slice(0,10);
resetShowcase();
localStorage.setItem('storeops_user','u-vf');
let list=await mockApi('/api/stores/val-fleuri/handover?status=ALL');
ok(Array.isArray(list.items)&&list.stats.pending>=1,'initial handover snapshot failed');
const created=await mockApi('/api/stores/val-fleuri/handover',{method:'POST',body:JSON.stringify({title:'Test passation bloquante',description:'Contrôle avant ouverture',category:'TECHNICAL',priority:'CRITICAL',blockingOpening:true,targetDate:today})});
ok(created.status==='OPEN'&&created.blocking_opening===1,'handover create failed');
list=await mockApi('/api/stores/val-fleuri/handover');
ok(list.stats.blocking>=1&&list.items.some(x=>x.id===created.id),'blocking handover not surfaced');
localStorage.setItem('storeops_user','u-emp-vf');
let denied=false;try{await mockApi('/api/stores/val-fleuri/handover',{method:'POST',body:JSON.stringify({title:'Interdit'})})}catch(e){denied=e.status===403}ok(denied,'employee must not create handover');
localStorage.setItem('storeops_user','u-vf');
let ack=await mockApi(`/api/handover/${created.id}/acknowledge`,{method:'POST'});ok(ack.status==='ACKNOWLEDGED'&&ack.acknowledged_by==='u-vf','handover acknowledge failed');
let missing=false;try{await mockApi(`/api/handover/${created.id}/resolve`,{method:'POST',body:JSON.stringify({note:''})})}catch(e){missing=e.status===400}ok(missing,'resolution note must be mandatory');
let resolved=await mockApi(`/api/handover/${created.id}/resolve`,{method:'POST',body:JSON.stringify({note:'Contrôle réalisé et équipement conforme.'})});ok(resolved.status==='RESOLVED'&&resolved.resolution_note,'handover resolution failed');
list=await mockApi('/api/stores/val-fleuri/handover');ok(!list.items.some(x=>x.id===created.id),'resolved handover should leave active list');
const review=await mockApi('/api/stores/val-fleuri/handover/review-closing',{method:'POST'});ok(!!review.day.handover_reviewed_at,'closing handover review failed');
console.log('StoreOps V1.25 showcase handover tests passed');
