import assert from 'node:assert/strict';
import {recommendReplenishment,decisionPresentation,weightedDailyVelocity} from '../services/replenishment-engine.mjs';
import {classifyProposal} from '../../frontend/analytics/replenishment.js';
assert.equal(weightedDailyVelocity({dailySales7:10,dailySales28:6}),8.6);
let r=recommendReplenishment({supplyMode:'WAREHOUSE',storeAvailable:3,supplyAvailable:31,confirmedInbound:0,dailySales7:11,dailySales28:9,leadTimeDays:1,safetyDays:1,packSize:6});
assert.equal(r.decision,'REPLENISH');
assert.equal(r.actionQty%6,0);
assert.equal(decisionPresentation(r).cta,'Préparer le transfert');
r=recommendReplenishment({supplyMode:'WAREHOUSE',storeAvailable:50,supplyAvailable:31,dailySales7:5,dailySales28:5,leadTimeDays:1,safetyDays:1,packSize:6});
assert.equal(r.decision,'OK');
r=recommendReplenishment({supplyMode:'DIRECT_SUPPLIER',storeAvailable:2,confirmedInbound:18,dailySales7:10,dailySales28:10,leadTimeDays:1,safetyDays:1,packSize:6,minOrderQty:24});
assert.equal(r.decision,'OK','minimum order must not create a need when stock and inbound cover demand');
assert.equal(r.recommendedQty,0);
r=recommendReplenishment({supplyMode:'WAREHOUSE',storeAvailable:0,supplyAvailable:0,dailySales7:10,dailySales28:10,leadTimeDays:1,safetyDays:1,packSize:6});
assert.equal(r.decision,'DC_BACKORDER');
assert.ok(r.actionQty>0);
r=recommendReplenishment({supplyMode:'WAREHOUSE',storeAvailable:0,supplyAvailable:5,dailySales7:10,dailySales28:10,leadTimeDays:1,safetyDays:1,packSize:6});
assert.equal(r.decision,'PARTIAL');
r=recommendReplenishment({supplyMode:'WAREHOUSE',storeAvailable:-2,supplyAvailable:100,dailySales7:10,dailySales28:10});
assert.equal(r.decision,'CHECK_STOCK');
r=recommendReplenishment({supplyMode:'WAREHOUSE',storeAvailable:3,supplyAvailable:100});
assert.equal(r.decision,'NEED_SALES_DATA');
r=recommendReplenishment({supplyMode:'WAREHOUSE',storeAvailable:null,supplyAvailable:100,dailySales7:10,dailySales28:10});
assert.equal(r.decision,'NEED_STOCK_DATA');
r=recommendReplenishment({supplyMode:'WAREHOUSE',storeAvailable:0,supplyAvailable:null,dailySales7:10,dailySales28:10});
assert.equal(r.decision,'NEED_SUPPLY_DATA');
assert.equal(r.metrics.remainingSupply,null);
const proposal={item:{inventoryUnit:'KG'},storeStock:{availableStock:0,incomingStock:0},merchandising:{assortment:{status:'ASSORTED'}},replenishment:{decision:'REPLENISH',actionQty:6,salesVelocity:{status:'READY',saleRows:10,quantityUnit:'kg'}}};
assert.equal(classifyProposal(proposal).quantity,6);
assert.equal(classifyProposal({...proposal,item:{inventoryUnit:'G'}}).quantity,null);
assert.equal(classifyProposal({...proposal,storeStock:{availableStock:0,incomingStock:null}}).quantity,null);
assert.equal(classifyProposal({...proposal,merchandising:{assortment:{status:'UNKNOWN'}}}).quantity,null);
assert.equal(classifyProposal({...proposal,replenishment:{...proposal.replenishment,decision:'DIRECT_ORDER'}}).quantity,null);
console.log('StoreOps replenishment recommendation engine contract OK');
