import assert from 'node:assert/strict';
import {mkdtempSync,readFileSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {assessNetworkStore,controlOverview,selectControlRows,networkClock} from '../../frontend/js/network-control-model.js';
const now=new Date('2026-10-09T10:00:00Z');
const healthy=id=>({id,code:id,name:`Magasin ${id}`,dataHealth:{network:true},day:{business_date:'2026-10-09',opening_status:'OPENED',closing_status:'NOT_STARTED'},staffing:{status:'OPENED',blocking:0},coldChain:{status:'OPENED',mismatch:0},cashOpening:{status:'OPENED',mismatch:0}});
const assess=row=>assessNetworkStore(row,{now});
// Use an established winter date: future Morocco DST forecasts differ across ICU versions.
assert.deepEqual(networkClock(new Date('2025-01-15T12:00:00Z')),{date:'2025-01-15',minute:780});
assert.equal(assess(healthy('ok')).control.state,'OK');
assert.equal(assess({...healthy('unknown'),dataHealth:{network:false}}).control.state,'UNKNOWN');
assert.equal(assess({...healthy('undated'),day:{opening_status:'OPENED'}}).control.state,'UNKNOWN');
assert.equal(assess({...healthy('old'),day:{business_date:'2026-10-08'}}).control.state,'UNKNOWN');
assert.equal(assess({...healthy('missing'),coldChain:{status:'NOT_STARTED'}}).control.state,'UNKNOWN');
assert.equal(assess({...healthy('cold'),coldChain:{status:'OPENED',mismatch:1}}).control.state,'CRITICAL');
assert.equal(assess({...healthy('expired'),dlc:{expired:1}}).control.state,'CRITICAL');
assert.equal(assess({...healthy('critical'),criticalIncidents:1}).control.state,'CRITICAL');
assert.equal(assess({...healthy('cash'),cash:{blocking:1}}).control.state,'OK','closing must not alarm before it starts');
assert.equal(assess({...healthy('staff'),staffing:{status:'PREPARING',blocking:1}}).control.state,'WARNING');
const unopened={...healthy('opening'),day:{business_date:'2026-10-09',opening_status:'NOT_STARTED'},commercial:{blocking:1}};
assert.equal(assess(unopened).control.state,'CRITICAL');
assert.equal(assess({...unopened,opening_time:'12:00'}).control.state,'OK','no overdue opening before scheduled time');
const pulse={status:'READY',businessDate:'2026-10-09',refreshedAt:now.toISOString(),comparison:{available:true},snapshot:{kpis:{netSales:1000,changeVsComparison:-15}}};
assert.equal(assess({...healthy('sales'),businessPulse:pulse}).control.state,'WARNING');
assert.equal(assess({...healthy('bad-comparison'),businessPulse:{...pulse,comparison:{available:false}}}).control.state,'OK');
assert.equal(assess({...healthy('stale-sales'),businessPulse:{...pulse,refreshedAt:'2026-10-09T09:00:00Z'}}).control.pulseReady,false);
assert.equal(assess({...healthy('future-sales'),businessPulse:{...pulse,refreshedAt:'2026-10-09T11:00:00Z'}}).control.pulseReady,false);
const rows=Array.from({length:50},(_,i)=>assess(healthy(String(i).padStart(2,'0'))));
rows[10]=assess({...healthy('10'),criticalIncidents:2});
rows[20]=assess({...healthy('20'),commercial:{pending:2}});
rows[30]=assess({...healthy('30'),dataHealth:{network:false}});
rows[40]=assess({...healthy('40'),businessPulse:{...pulse,snapshot:{kpis:{netSales:1000}}}});
assert.deepEqual(controlOverview(rows).counts,{CRITICAL:1,WARNING:1,UNKNOWN:1,OK:47});
assert.equal(controlOverview(rows).sales,1000,'partial coverage must not count missing stores as zero');
assert.equal(controlOverview(rows).salesCoverage,1);
assert.equal(controlOverview(rows.filter(r=>r.id!=='40')).sales,null);
assert.deepEqual(selectControlRows(rows).slice(0,3).map(r=>r.id),['10','20','30']);
assert.equal(selectControlRows(rows,{filter:'ATTENTION'}).length,3);
assert.equal(selectControlRows(rows,{query:'Magasin 30'})[0].id,'30');
process.env.STOREOPS_DB=join(mkdtempSync(join(tmpdir(),'storeops-network-')),'test.db');
const {networkControlSnapshot}=await import('../services/network-control.mjs');
const {db}=await import('../db.mjs');
const before=db.prepare('SELECT total_changes() changes').get().changes;
const snap=networkControlSnapshot('synthetic-store','2026-10-09');
assert.equal(snap.staffing.status,'NOT_STARTED');
assert.equal(snap.coldChain.status,'NOT_STARTED');
assert.equal(snap.cashOpening.status,'NOT_STARTED');
assert.equal(snap.businessPulse,null);
assert.equal(db.prepare('SELECT total_changes() changes').get().changes,before,'snapshot must not start workflows or mutate local controls');
const source=readFileSync(new URL('../services/network-control.mjs',import.meta.url),'utf8');
assert.doesNotMatch(source,/fetch\(|refreshCommercial|getBusinessPulse|await /,'central overview must not wait on external enrichment');
db.close();
console.log('Network control room: 50 stores, priorities, unknown data, same-period sales and read-only local snapshot passed');
